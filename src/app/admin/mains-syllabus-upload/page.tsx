'use client';

import { useState } from 'react';
import { adminApplyMainsSyllabusJson } from '@/actions/mains-actions';
import { Button } from '@/components/ui/button';
import { Textarea } from '@/components/ui/textarea';
import { Card, CardContent, CardHeader, CardTitle, CardDescription } from '@/components/ui/card';
import { Alert, AlertTitle, AlertDescription } from '@/components/ui/alert';
import { Upload, CheckCircle2, AlertTriangle, FileJson, Copy } from 'lucide-react';
import { toast } from 'sonner';
import { MainsSyllabusProgressTracker } from '@/app/admin/mains/MainsSyllabusProgressTracker';

const UPSC_SYLLABUS_DECODER_PROMPT = `You are an Elite UPSC IAS Topper and a Master Curriculum Architect. Your task is to deeply decode the raw, unstructured UPSC General Studies syllabus into a highly structured, actionable, and granular curriculum format.

UPSC provides the syllabus as continuous vague bullet points without strict "Units". Your job is to decode it exactly how a Rank 1 candidate does:
1. **Group the bullets into logical "Macro-Themes"** (e.g., GS 1 into Indian Heritage, Modern History, World History, Indian Society, Geography). These will be our \`units\`.
2. **Break down the vague bullets into Granular "Micro-Topics"**. For example, do not just output "Modern Indian history from mid-18th century". Break it down into 4-6 specific actionable topics like "Decline of Mughals & Rise of Regional States", "Advent of Europeans", "Revolt of 1857", etc. These will be our \`topics_en\` and \`topics_hi\`.

### JSON Schema Mandate:
You MUST output ONLY a valid JSON object matching the exact structure below. Do not include markdown fences (\`\`\`json) or any text outside the JSON.

{
  "papers": [
    {
      "paper_number": 2, // IMPORTANT: GS 1 is Paper 2, GS 2 is Paper 3, GS 3 is Paper 4, GS 4 is Paper 5. Or use 1, 2, 3, 4 based on your preference.
      "paper_title_en": "General Studies I (Paper II)",
      "paper_title_hi": "सामान्य अध्ययन I (पेपर II)",
      "total_marks": 250,
      "duration_minutes": 180,
      "parts": [
        {
          "part": "A", // Use "A" as a default part container since UPSC doesn't have strict parts.
          "units": [
            {
              "unit_number": 1, // Auto-increment per Macro-Theme
              "unit_title_en": "Indian Heritage and Culture", // Provide a deeply analytical title
              "unit_title_hi": "भारतीय विरासत और संस्कृति",
              "topics": [
                {
                  "topic_number": 1,
                  "title_hi": "दृश्य कला: प्राचीन से आधुनिक भारत तक वास्तुकला, मूर्तिकला और चित्रकला",
                  "title_en": "Visual Arts: Architecture, Sculpture & Painting from Ancient to Modern India"
                },
                {
                  "topic_number": 2,
                  "title_hi": "प्रदर्शन कला: शास्त्रीय नृत्य, संगीत और रंगमंच",
                  "title_en": "Performing Arts: Classical Dances, Music & Theatre"
                }
              ]
            }
          ]
        }
      ]
    }
  ]
}

### Elite Decoding Rules:
1. **Macro-Themes (\`units\`)**: Create 4 to 7 Macro-Themes per paper. Give them academic, UPSC-standard titles (e.g., "Post-Independence Consolidation & Nation Building").
2. **Granular Breakdown (\`topics\`)**: Extract the "hidden" syllabus. A single UPSC bullet point usually contains 3-6 distinct sub-topics. Break them down logically so a student can study them one by one.
3. **Bilingual Precision**: Provide exact, high-quality official Hindi translations for every English title and topic. 
4. **Interlinking Mindset**: Structure the order of the topics so they flow logically (Chronological for History, Foundational to Applied for Geography/Economy). 

Here is the raw UPSC syllabus text for [INSERT PAPER NAME HERE, e.g., GS 1]:
[PASTE RAW SYLLABUS TEXT HERE]`;

export default function MainsSyllabusUploadPage() {
  const [jsonInput, setJsonInput] = useState('');
  const [status, setStatus] = useState<{ type: 'success' | 'error' | null; msg: string }>({
    type: null,
    msg: '',
  });
  const [loading, setLoading] = useState(false);

  async function handleUpload() {
    if (!jsonInput) {
      setStatus({ type: 'error', msg: 'Please paste the JSON generated by AI.' });
      return;
    }

    setLoading(true);
    setStatus({ type: null, msg: '' });

    try {
      const result = await adminApplyMainsSyllabusJson(jsonInput);
      if (result.success) {
        setStatus({ type: 'success', msg: result.message || 'Syllabus successfully uploaded!' });
        setJsonInput(''); // Clear on success
      } else {
        setStatus({ type: 'error', msg: result.error || 'Failed to upload syllabus' });
      }
    } catch (e: any) {
      setStatus({ type: 'error', msg: e.message });
    } finally {
      setLoading(false);
    }
  }

  return (
    <div className="container mx-auto max-w-4xl p-6">
      <div className="mb-6">
        <h1 className="text-3xl font-bold tracking-tight text-foreground">Mains Syllabus Upload</h1>
        <p className="mt-2 text-muted-foreground">
          Paste the decoded JSON syllabus from AI to instantly build the curriculum tree (Papers, Units, Topics).
        </p>
      </div>

      {/* Overview Tracker placed at the top */}
      <div className="mb-8">
        <MainsSyllabusProgressTracker />
      </div>

      <div className="grid gap-6 md:grid-cols-3">
        <div className="md:col-span-2">
          <Card>
            <CardHeader className="bg-muted/50 border-b pb-4">
              <CardTitle className="flex items-center gap-2">
                <FileJson className="h-5 w-5 text-primary" />
                Syllabus JSON Payload
              </CardTitle>
              <CardDescription>
                Paste the full JSON object containing the "papers" array here.
              </CardDescription>
            </CardHeader>
            <CardContent className="space-y-4 pt-6">
              <Textarea
                placeholder='{
  "papers": [
    {
      "paper_number": 4,
      ...
    }
  ]
}'
                className="h-[400px] overflow-y-auto font-mono text-xs leading-relaxed resize-none"
                value={jsonInput}
                onChange={(e) => setJsonInput(e.target.value)}
              />

              {status.type && (
                <Alert
                  variant={status.type === 'error' ? 'destructive' : 'default'}
                  className={status.type === 'success' ? 'border-green-500 bg-green-50 text-green-800' : ''}
                >
                  {status.type === 'success' ? (
                    <CheckCircle2 className="h-4 w-4 text-green-600" />
                  ) : (
                    <AlertTriangle className="h-4 w-4" />
                  )}
                  <AlertTitle>{status.type === 'success' ? 'Upload Successful' : 'Upload Failed'}</AlertTitle>
                  <AlertDescription>{status.msg}</AlertDescription>
                </Alert>
              )}

              <Button 
                onClick={handleUpload} 
                disabled={loading} 
                className="w-full"
              >
                {loading ? 'Uploading & Structuring...' : (
                  <>
                    <Upload className="mr-2 h-4 w-4" />
                    Upload Syllabus to Database
                  </>
                )}
              </Button>
            </CardContent>
          </Card>
        </div>

        <div className="space-y-6">
          <Card className="bg-muted/50">
            <CardHeader>
              <CardTitle className="text-base">How to get the JSON?</CardTitle>
            </CardHeader>
            <CardContent className="text-sm text-muted-foreground space-y-3">
              <p>1. Copy the <strong>Elite UPSC Syllabus Decoder Prompt</strong> using the button below.</p>
              <p>2. Paste it in ChatGPT/Claude along with the raw syllabus text from the UPSC PDF.</p>
              <p>3. AI will output a clean, deeply-decoded JSON structure breaking down vague bullets into micro-topics.</p>
              <p>4. Paste that JSON here to automatically organize it into the database!</p>

              <Button
                variant="outline"
                className="w-full mt-4 flex items-center gap-2"
                onClick={() => {
                  navigator.clipboard.writeText(UPSC_SYLLABUS_DECODER_PROMPT);
                  toast.success('Prompt Copied', { description: 'Paste in ChatGPT with raw syllabus text.' });
                }}
              >
                <Copy className="h-4 w-4" /> Copy Master Prompt
              </Button>
            </CardContent>
          </Card>
        </div>
      </div>
    </div>
  );
}
